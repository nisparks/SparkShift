"""Write an OpenFOAM (ESI v2606) case for the CPAP duct: snappyHexMesh + simpleFoam, k-omega SST.

Usage: python cfd_case.py <domain dir> <case dir> --flows 180,120,240 [--iters 1500,800,800] [--np 10]

Air at 20 C: nu 1.5e-5 m2/s, rho 1.2 kg/m3 (pressures in the case are kinematic, p/rho).
Inlet: the hose section's end, a set volumetric flow with 5 % turbulence intensity and a mixing length of
0.07 x the 16.4 mm bore. The open-air faces around the nozzle: total pressure 0 (room), inflow or outflow.
"""
import argparse
import json
import math
import shutil
from pathlib import Path

NU, RHO = 1.5e-5, 1.2
INTENSITY = 0.05
BASE = 1.0e-3                 # background cell (m); level 1 = 0.5 mm, level 2 = 0.25 mm
PAD = 1.5e-3
HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  SparkShift CPAP duct CFD (generated by cfd_case.py)
\\*---------------------------------------------------------------------------*/
FoamFile {{ version 2.0; format ascii; class {cls}; object {obj}; }}
"""


def write(path, obj, body, cls="dictionary"):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER.format(cls=cls, obj=obj) + body, newline="\n")


def inlet_turbulence(q_lpm, area_mm2, d_mm):
    u = q_lpm / 60000.0 / (area_mm2 * 1e-6)
    k = 1.5 * (INTENSITY * u) ** 2
    lm = 0.07 * d_mm * 1e-3
    omega = math.sqrt(k) / (0.09 ** 0.25 * lm)
    return u, k, omega, lm


def main():
    p = argparse.ArgumentParser()
    p.add_argument("domain")
    p.add_argument("case")
    p.add_argument("--flows", default="180,120,240")
    p.add_argument("--interval", type=int, default=600, help="iterations per later stage; the first gets two")
    p.add_argument("--upwind", type=int, default=300, help="first-order iterations before second order")
    p.add_argument("--np", type=int, default=10)
    p.add_argument("--wall-levels", default="1 2", help="snappy (min max) refinement on walls")
    p.add_argument("--zone-level", type=int, default=2, help="refinement inside the jet/nozzle zone")
    a = p.parse_args()
    dom, case = Path(a.domain), Path(a.case)
    meta = json.loads((dom / "domain.json").read_text())
    flows = [float(v) for v in a.flows.split(",")]
    iters = [2 * a.interval] + [a.interval] * (len(flows) - 1)
    if case.exists():
        shutil.rmtree(case)
    (case / "constant" / "triSurface").mkdir(parents=True)
    shutil.copy(dom / "domain.stl", case / "constant" / "triSurface" / "domain.stl")
    shutil.copy(dom / "domain.json", case / "domain.json")

    # ---- background mesh: the domain's bounds padded by 1.5 mm, 1 mm cells
    b = [v * 1e-3 for v in meta["bounds_mm"]]
    lo = [b[0] - PAD, b[2] - PAD, b[4] - PAD]
    n = [math.ceil((b[2 * i + 1] + PAD - lo[i]) / BASE) for i in range(3)]
    hi = [lo[i] + n[i] * BASE for i in range(3)]
    verts = [(lo[0], lo[1], lo[2]), (hi[0], lo[1], lo[2]), (hi[0], hi[1], lo[2]), (lo[0], hi[1], lo[2]),
             (lo[0], lo[1], hi[2]), (hi[0], lo[1], hi[2]), (hi[0], hi[1], hi[2]), (lo[0], hi[1], hi[2])]
    write(case / "system" / "blockMeshDict", "blockMeshDict", f"""
scale 1;
vertices ( {' '.join(f'({x:.6f} {y:.6f} {z:.6f})' for x, y, z in verts)} );
blocks ( hex (0 1 2 3 4 5 6 7) ({n[0]} {n[1]} {n[2]}) simpleGrading (1 1 1) );
edges ();
boundary ( background {{ type patch; faces ( (0 3 2 1) (4 5 6 7) (0 1 5 4) (2 3 7 6) (0 4 7 3) (1 2 6 5) ); }} );
mergePatchPairs ();
""")
    write(case / "system" / "surfaceFeatureExtractDict", "surfaceFeatureExtractDict", """
domain.stl
{
    extractionMethod    extractFromSurface;
    includedAngle       150;
    subsetFeatures { nonManifoldEdges no; openEdges yes; }
    writeObj            no;
}
""")
    # ---- snappyHexMesh: walls 0.5 mm (0.25 at sharp curvature), 0.25 mm around the jets, nozzle and slot
    loc = meta["location_in_mesh_m"]
    loc = [loc[0] + 0.37e-3, loc[1] + 0.23e-3, loc[2] + 0.13e-3]
    tip = meta["nozzle_tip_z_mm"] * 1e-3
    bed = meta["bed"]
    bed_region = " bed { name bed; }" if bed else ""
    bed_level = "\n                bed     { level (2 2); patchInfo { type wall; } }" if bed else ""
    write(case / "system" / "snappyHexMeshDict", "snappyHexMeshDict", f"""
castellatedMesh true;
snap            true;
addLayers       false;

geometry
{{
    domain.stl
    {{
        type triSurfaceMesh;
        name domain;
        regions {{ inlet {{ name inlet; }} ambient {{ name ambient; }} walls {{ name walls; }}{bed_region} }}
    }}
    nozzleZone {{ type box; min (-0.0160 0.0120 {tip - 0.0050:.5f}); max (0.0160 0.0330 {tip + 0.0090:.5f}); }}
}}

castellatedMeshControls
{{
    maxLocalCells       4000000;
    maxGlobalCells      20000000;
    minRefinementCells  10;
    maxLoadUnbalance    0.10;
    nCellsBetweenLevels 3;
    features ( {{ file "domain.eMesh"; level 2; }} );
    refinementSurfaces
    {{
        domain
        {{
            level (1 1);
            regions
            {{
                inlet   {{ level (1 1); patchInfo {{ type patch; }} }}
                ambient {{ level (0 0); patchInfo {{ type patch; }} }}
                walls   {{ level ({a.wall_levels}); patchInfo {{ type wall; }} }}{bed_level}
            }}
        }}
    }}
    resolveFeatureAngle 30;
    refinementRegions {{ nozzleZone {{ mode inside; levels ((1e15 {a.zone_level})); }} }}
    locationInMesh ({loc[0]:.6f} {loc[1]:.6f} {loc[2]:.6f});
    allowFreeStandingZoneFaces true;
}}

snapControls
{{
    nSmoothPatch 3;
    tolerance 2.0;
    nSolveIter 50;
    nRelaxIter 5;
    nFeatureSnapIter 10;
    implicitFeatureSnap false;
    explicitFeatureSnap true;
    multiRegionFeatureSnap true;
}}

addLayersControls
{{
    relativeSizes true;
    layers {{ }}
    expansionRatio 1.2;
    finalLayerThickness 0.5;
    minThickness 0.1;
    nGrow 0;
    featureAngle 60;
    nRelaxIter 3;
    nSmoothSurfaceNormals 1;
    nSmoothNormals 3;
    nSmoothThickness 10;
    maxFaceThicknessRatio 0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle 90;
    nBufferCellsNoExtrude 0;
    nLayerIter 50;
}}

meshQualityControls
{{
    #includeEtc "caseDicts/meshQualityDict"
    relaxed {{ maxNonOrtho 75; }}
    nSmoothScale 4;
    errorReduction 0.75;
}}

mergeTolerance 1e-6;
""")
    write(case / "system" / "decomposeParDict", "decomposeParDict", f"""
numberOfSubdomains {a.np};
method scotch;
""")
    write(case / "system" / "meshQualityDict", "meshQualityDict", """
#includeEtc "caseDicts/meshQualityDict"
""")
    # ---- numerics: first-order upwind to settle the flow, then second order (the runner swaps fvSchemes at UPWIND)
    schemes = """
ddtSchemes { default steadyState; }
gradSchemes { default cellLimited Gauss linear 1; }
divSchemes
{
    default none;
    div(phi,U) bounded Gauss %s;
    turbulence bounded Gauss %s;
    div(phi,k) $turbulence;
    div(phi,omega) $turbulence;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear limited corrected 0.5; }
interpolationSchemes { default linear; }
snGradSchemes { default limited corrected 0.5; }
wallDist { method meshWave; }
"""
    write(case / "system" / "fvSchemes", "fvSchemes", schemes % ("upwind", "upwind"))
    write(case / "system" / "fvSchemes.first", "fvSchemes", schemes % ("upwind", "upwind"))
    write(case / "system" / "fvSchemes.second", "fvSchemes", schemes % ("linearUpwindV grad(U)", "limitedLinear 1"))
    write(case / "system" / "fvSolution", "fvSolution", """
solvers
{
    p { solver GAMG; smoother GaussSeidel; tolerance 1e-7; relTol 0.01; }
    Phi { $p; }
    "(U|k|omega)" { solver smoothSolver; smoother GaussSeidel; tolerance 1e-8; relTol 0.1; nSweeps 1; }
}
SIMPLE { nNonOrthogonalCorrectors 1; consistent no; }
potentialFlow { nNonOrthogonalCorrectors 10; }
relaxationFactors { fields { p 0.3; } equations { U 0.7; k 0.5; omega 0.5; } }
cache { grad(U); }
""")
    total = sum(iters)
    write(case / "system" / "controlDict", "controlDict", f"""
application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {total};
deltaT          1;
writeControl    timeStep;
writeInterval   {a.interval};
purgeWrite      0;
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{
    pTotal
    {{
        type            pressure;
        libs            (fieldFunctionObjects);
        mode            total;
        rho             rhoInf;
        rhoInf          1;
        result          pTotal;
        writeControl    writeTime;
    }}
    inletAvg
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            inlet;
        operation       areaAverage;
        fields          (p pTotal);
        writeFields     false;
        log             false;
        writeControl    timeStep;
        writeInterval   5;
    }}
    flows
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            ambient;
        operation       sum;
        fields          (phi);
        writeFields     false;
        log             false;
        writeControl    timeStep;
        writeInterval   5;
    }}
    residuals
    {{
        type            solverInfo;
        libs            (utilityFunctionObjects);
        fields          (U p k omega);
    }}
    yPlus
    {{
        type            yPlus;
        libs            (fieldFunctionObjects);
        writeControl    writeTime;
        log             false;
    }}
}}
// planned stages (iterations, L/min): {list(zip(iters, flows))}; total {total}
""")
    write(case / "constant" / "transportProperties", "transportProperties", f"""
transportModel  Newtonian;
nu              {NU};
""")
    write(case / "constant" / "turbulenceProperties", "turbulenceProperties", """
simulationType  RAS;
RAS { RASModel kOmegaSST; turbulence on; printCoeffs on; }
""")
    # ---- initial and boundary conditions; the inlet flow steps through the stages (time = iteration)
    area, d = meta["inlet"]["area_mm2"], 2 * meta["inlet"]["radius_mm"]
    u0, k0, w0, lm = inlet_turbulence(flows[0], area, d)
    kamb, wamb = 1.5e-4, 22.0
    table, t = [], 0
    for i, (q, it) in enumerate(zip(flows, iters)):
        table.append((t + (0.5 if i else 0), q / 60000.0))
        t += it
        table.append((t, q / 60000.0))
    table_s = " ".join(f"({tt:g} {qq:.8e})" for tt, qq in table)
    zero = case / "0.orig"
    walls = '"(walls|bed)"'
    write(zero / "U", "U", f"""
dimensions [0 1 -1 0 0 0 0];
internalField uniform (0 0 0);
boundaryField
{{
    #includeEtc "caseDicts/setConstraintTypes"
    inlet {{ type flowRateInletVelocity; volumetricFlowRate table ( {table_s} ); extrapolateProfile no;
             value uniform (0 0 0); }}
    ambient {{ type pressureInletOutletVelocity; value uniform (0 0 0); }}
    {walls} {{ type noSlip; }}
    background {{ type zeroGradient; }}
}}
""", cls="volVectorField")
    write(zero / "p", "p", """
dimensions [0 2 -2 0 0 0 0];
internalField uniform 0;
boundaryField
{
    #includeEtc "caseDicts/setConstraintTypes"
    inlet { type zeroGradient; }
    ambient { type totalPressure; p0 uniform 0; value uniform 0; }
    "(walls|bed)" { type zeroGradient; }
    background { type zeroGradient; }
}
""", cls="volScalarField")
    write(zero / "k", "k", f"""
dimensions [0 2 -2 0 0 0 0];
internalField uniform {kamb};
boundaryField
{{
    #includeEtc "caseDicts/setConstraintTypes"
    inlet {{ type turbulentIntensityKineticEnergyInlet; intensity {INTENSITY}; value uniform {k0:.6e}; }}
    ambient {{ type inletOutlet; inletValue uniform {kamb}; value uniform {kamb}; }}
    {walls} {{ type kqRWallFunction; value uniform {kamb}; }}
    background {{ type zeroGradient; }}
}}
""", cls="volScalarField")
    write(zero / "omega", "omega", f"""
dimensions [0 0 -1 0 0 0 0];
internalField uniform {wamb};
boundaryField
{{
    #includeEtc "caseDicts/setConstraintTypes"
    inlet {{ type turbulentMixingLengthFrequencyInlet; mixingLength {lm:.6e}; value uniform {w0:.6e}; }}
    ambient {{ type inletOutlet; inletValue uniform {wamb}; value uniform {wamb}; }}
    {walls} {{ type omegaWallFunction; value uniform {wamb}; }}
    background {{ type zeroGradient; }}
}}
""", cls="volScalarField")
    write(zero / "nut", "nut", f"""
dimensions [0 2 -1 0 0 0 0];
internalField uniform 0;
boundaryField
{{
    #includeEtc "caseDicts/setConstraintTypes"
    inlet {{ type calculated; value uniform 0; }}
    ambient {{ type calculated; value uniform 0; }}
    {walls} {{ type nutUSpaldingWallFunction; value uniform 0; }}
    background {{ type calculated; value uniform 0; }}
}}
""", cls="volScalarField")
    stages = []
    t = 0
    for q, it in zip(flows, iters):
        t += it
        stages.append({"lpm": q, "end": t, "q_m3s": q / 60000.0, "inlet_velocity_ms": inlet_turbulence(q, area, d)[0]})
    (case / "stages.json").write_text(json.dumps({"np": a.np, "stages": stages, "nu": NU, "rho": RHO,
                                                   "intensity": INTENSITY, "mixing_length_m": lm,
                                                   "background_cells": n}, indent=1))
    (case / "np.txt").write_text(f"{a.np}\n", newline="\n")
    (case / "upwind.txt").write_text(f"{a.upwind}\n", newline="\n")
    (case / "times.txt").write_text(",".join(str(s["end"]) for s in stages) + "\n", newline="\n")
    print(json.dumps({"case": str(case), "background_cells": n, "stages": stages}, indent=1))


if __name__ == "__main__":
    main()
